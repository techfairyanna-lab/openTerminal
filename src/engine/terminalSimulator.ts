// ─────────────────────────────────────────────
//  PIPE SUPPORT  (cmd1 | cmd2)
// ─────────────────────────────────────────────
function executePipe(left: string, right: string): CommandResult {
  const leftResult = executeSingle(left);
  if (!leftResult || leftResult.type === "error") return leftResult;

  const { cmd, args, flags, rawArgs } = parseCommand(right.trim());
  const handler = commands[cmd];
  if (!handler) return err(`bash: ${cmd}: command not found`);

  const tempPath = "/__pipe_input__";
  state.overlay[tempPath] = (leftResult as any).text || "";
  
  const fileOpResult = fileOp([tempPath], content => {
    state.overlay[tempPath] = content;
    return; // returning void instead of null
  });

  let result: CommandResult = null;
  if (cmd === "grep") result = handler([args[0], tempPath], flags, rawArgs);
  else if (cmd === "sort" || cmd === "wc" || cmd === "head" || cmd === "tail" || cmd === "uniq" || cmd === "nl") result = handler([tempPath], flags, rawArgs);
  else if (cmd === "cut") result = handler([...rawArgs.filter(a => !a.startsWith("-")), tempPath], flags, rawArgs);
  else result = info(`Pipe to '${cmd}' is partially simulated`);
  
  delete state.overlay[tempPath];
  return result;
}

// ─────────────────────────────────────────────
//  REDIRECTION SUPPORT  (> and >>)
// ─────────────────────────────────────────────
function executeRedirect(cmdStr: string, file: string, append: boolean): CommandResult {
  const result = executeSingle(cmdStr.trim());
  if (!result || result.type === "error") return result;
  const abs = normalizePath(file.trim());
  const content = (result as any).text || "";
  if (append) {
    const existing = isFile(abs) ? (getNode(abs) as string) : "";
    state.overlay[abs] = existing + content + "\n";
  } else {
    state.overlay[abs] = content + "\n";
  }
  return out(`Output written to ${file.trim()}`);
}

// ─────────────────────────────────────────────
//  COMMAND PARSER
// ─────────────────────────────────────────────
function parseCommand(input: string) {
  const firstWord = input.trim().split(/\s+/)[0];
  if (state.aliases[firstWord]) {
    input = state.aliases[firstWord] + input.slice(firstWord.length);
  }

  const tokens: string[] = [];
  let current = "";
  let inSingle = false, inDouble = false;
  for (let i = 0; i < input.length; i++) {
    const c = input[i];
    if (c === "'" && !inDouble) { inSingle = !inSingle; continue; }
    if (c === '"' && !inSingle) { inDouble = !inDouble; continue; }
    if (c === " " && !inSingle && !inDouble) {
      if (current) { tokens.push(current); current = ""; }
    } else {
      current += c;
    }
  }
  if (current) tokens.push(current);

  const [cmd, ...rest] = tokens;
  const flags = rest.filter(t => t.startsWith("-"));
  const args = rest.filter(t => !t.startsWith("-"));

  return { cmd, args, flags, rawArgs: rest };
}

// ─────────────────────────────────────────────
//  SINGLE COMMAND EXECUTOR
// ─────────────────────────────────────────────
function executeSingle(input: string): CommandResult {
  const { cmd, args, flags, rawArgs } = parseCommand(input);
  if (!cmd) return null;

  const handler = commands[cmd];
  if (!handler) {
    if (cmd.startsWith("./")) {
      const abs = normalizePath(cmd.slice(2));
      if (isFile(abs)) return out((getNode(abs) as string).split("\n").filter(l => !l.startsWith("#") && l.trim()).map(l => {
        if (l.startsWith("echo ")) return l.replace(/^echo /, "").replace(/["']/g, "");
        return "";
      }).filter(Boolean).join("\n"));
      return err(`bash: ${cmd}: No such file or directory`);
    }
    return err(`bash: ${cmd}: command not found`);
  }

  return handler(args, flags, rawArgs);
}

// ─────────────────────────────────────────────
//  MAIN EXECUTE FUNCTION
// ─────────────────────────────────────────────
export function executeCommand(input: string): CommandResult {
  const trimmed = input.trim();
  if (!trimmed) return null;

  state.history.push(trimmed);

  if (trimmed.includes("|")) {
    const parts = trimmed.split("|");
    let result: CommandResult = null;
    for (let i = 0; i < parts.length; i++) {
      if (i === 0) result = executeSingle(parts[0].trim());
      else {
        const tempPath = "/__pipe__";
        if (result && 'text' in result) state.overlay[tempPath] = result.text;
        const { cmd, args, flags, rawArgs } = parseCommand(parts[i].trim());
        const handler = commands[cmd];
        if (!handler) { result = err(`bash: ${cmd}: command not found`); break; }
        const newArgs = (result && 'text' in result) ? [...args, tempPath] : args;
        result = handler(newArgs, flags, rawArgs);
        delete state.overlay[tempPath];
      }
    }
    return result;
  }

  if (trimmed.includes(">>")) {
    const [left, right] = trimmed.split(">>", 2);
    return executeRedirect(left, right, true);
  }

  if (trimmed.includes(">") && !trimmed.includes("2>")) {
    const [left, right] = trimmed.split(">", 2);
    return executeRedirect(left, right, false);
  }

  const cmd2null = trimmed.replace(/\s+2>\/dev\/null/, "").replace(/\s+2>&1/, "");
  return executeSingle(cmd2null);
}

// ─────────────────────────────────────────────
//  TAB AUTOCOMPLETION
// ─────────────────────────────────────────────
export function getCompletions(input: string): string[] {
  const parts = input.trim().split(/\s+/);
  const cmd = parts[0];
  
  if (parts.length === 1) {
    return Object.keys(commands).filter(c => c.startsWith(cmd));
  }

  if (["ls", "cd", "cat", "rm", "mkdir", "touch", "nano"].includes(cmd)) {
    const currentArg = parts[parts.length - 1];
    const absPath = normalizePath(currentArg);
    const parentDir = currentArg.endsWith("/") ? absPath : parentPath(absPath);
    
    if (isDir(parentDir)) {
      const entries = listDir(parentDir) || [];
      const partialName = basename(absPath);
      return entries.filter(e => e.startsWith(partialName));
    }
  }
  
  return [];
}

