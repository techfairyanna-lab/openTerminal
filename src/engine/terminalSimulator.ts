export function getAllSimulatedFiles(): { name: string, content: string }[] {
  const files: { name: string, content: string }[] = [];
  function walk(p: string, prefix: string) {
    const entries = listDir(p) || [];
    for (const name of entries) {
      const childPath = p === "/" ? "/" + name : p + "/" + name;
      const displayPath = prefix ? `${prefix}/${name}` : name;
      if (isFile(childPath)) {
        files.push({ name: displayPath, content: (getNode(childPath) as string) || "" });
      } else if (isDir(childPath)) {
        walk(childPath, displayPath);
      }
    }
  }
  walk("/", "");
  return files;
}

