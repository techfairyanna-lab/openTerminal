commands.tree = (args, flags) => {
  const targetArg = args[0] || ".";
  const abs = normalizePath(targetArg);
  if (!isDir(abs)) return err(`tree: '${targetArg}': not a directory`);
  const showHidden = flags.includes("-a");
  const dirOnly = flags.includes("-d");

  let fileCount = 0, dirCount = 0;

  function buildTree(p: string, prefix: string): string {
    const entries = listDir(p) || [];
    const visible = showHidden ? entries : entries.filter(e => !e.startsWith("."));
    let result = "";
    
    visible.forEach((name, i) => {
      const childPath = p === "/" ? "/" + name : p + "/" + name;
      const isLast = i === visible.length - 1;
      const connector = isLast ? "└── " : "├── ";
      const childIsDir = isDir(childPath);
      
      if (dirOnly && !childIsDir) return;
      
      const coloredName = childIsDir ? `\x1b[01;34m${name}\x1b[0m` : name;
      result += prefix + connector + coloredName + "\n";
      
      if (childIsDir) { 
        dirCount++; 
        result += buildTree(childPath, prefix + (isLast ? "    " : "│   ")); 
      } else {
        fileCount++;
      }
    });
    return result;
  }

  const rootName = basename(abs);
  const output = `\x1b[01;34m${rootName}\x1b[0m\n` + buildTree(abs, "");
  return out(output + `\n${dirCount} director${dirCount === 1 ? "y" : "ies"}, ${fileCount} file${fileCount === 1 ? "" : "s"}`);
};

