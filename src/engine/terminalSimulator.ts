const commands: Record<string, (args: string[], flags: string[], rawArgs: string[]) => CommandResult> = {};

commands.echo = (args, flags) => {
  let text = args.join(" ");
  text = text.replace(/\$([A-Z_][A-Z0-9_]*)/g, (_, name) =>
    state.env[name as string] !== undefined ? state.env[name as string] : ""
  );
  text = text.replace(/\$\(\((.+?)\)\)/g, (_, expr) => {
    try { return String(Function('"use strict"; return (' + expr + ')')()) }
    catch { return "0" }
  });
  text = text.replace(/^["']|["']$/g, "");

  if (flags.includes("-n")) return out(text);
  if (flags.includes("-e")) {
    text = text.replace(/\\n/g, "\n").replace(/\\t/g, "\t");
  }
  return out(text);
};

commands.clear = () => ({ type: "clear" });
commands.pwd = () => out(state.cwd);

commands.cd = (args) => {
  let target = args[0] || state.env.HOME;
  if (target === "-") target = state.env.OLDPWD || state.env.HOME;
  const abs = normalizePath(target);

  if (state.protected.has(abs)) return err(`cd: ${abs}: Permission denied`);

  if (!isDir(abs)) {
    if (isFile(abs)) return err(`cd: ${abs}: Not a directory`);
    return err(`cd: ${args[0]}: No such file or directory`);
  }

  state.env.OLDPWD = state.cwd;
  state.cwd = abs;
  state.env.PWD = abs;
  return null;
};

commands.ls = (args, flags, rawArgs) => {
  const showHidden = flags.includes("-a") || flags.includes("-A");
  const longFormat = flags.includes("-l");
  const recursive = flags.includes("-R");

  const targetArg = args[0] || state.cwd;
  const abs = normalizePath(targetArg);

  if (state.protected.has(abs)) return err(`ls: cannot open directory '${targetArg}': Permission denied`);

  if (isFile(abs)) {
    if (longFormat) return out(formatLong(abs, basename(abs)));
    return out(basename(abs));
  }

  if (!isDir(abs)) return err(`ls: cannot access '${targetArg}': No such file or directory`);

  const entries = listDir(abs) || [];
  const visible = showHidden
    ? (flags.includes("-a") ? [".", "..", ...entries] : entries)
    : entries.filter(e => !e.startsWith("."));

  if (longFormat) {
    const lines = ["total " + visible.length * 4];
    for (const name of visible) {
      const childPath = abs === "/" ? "/" + name : abs + "/" + name;
      lines.push(formatLong(childPath, name));
    }
    return out(lines.join("\n"));
  }

  if (recursive) {
    let output = abs + ":\n" + colorNames(visible, abs).join("  ");
    for (const name of visible.filter(n => !n.startsWith("."))) {
      const childPath = abs === "/" ? "/" + name : abs + "/" + name;
      if (isDir(childPath)) {
        const sub = commands.ls([childPath], flags, rawArgs);
        if (sub && 'text' in sub) output += "\n\n" + (sub.text || "");
      }
    }
    return out(output);
  }

  return out(colorNames(visible, abs).join("  "));
};

function isExecutable(absPath: string): boolean {
  if (absPath.endsWith(".sh")) return true;
  const content = getNode(absPath);
  if (typeof content === "string" && content.startsWith("#!/")) return true;
  return false;
}

function colorNames(names: string[], parentAbs: string): string[] {
  return names.map(name => {
    const childPath = parentAbs === "/" ? "/" + name : parentAbs + "/" + name;
    if (isDir(childPath)) return `\x1b[01;34m${name}\x1b[0m`;
    if (isExecutable(childPath)) return `\x1b[01;32m${name}\x1b[0m`;
    if (/\.(tar|gz|zip|7z|rar|bz2|xz)$/.test(name)) return `\x1b[01;31m${name}\x1b[0m`;
    if (/\.(png|jpg|jpeg|gif|mp4|mkv|webm|svg)$/.test(name)) return `\x1b[01;35m${name}\x1b[0m`;
    if (/\.(mp3|wav|ogg|flac)$/.test(name)) return `\x1b[01;36m${name}\x1b[0m`;
    return name;
  });
}

function formatLong(absPath: string, name: string): string {
  const dir = isDir(absPath);
  const type = dir ? "d" : "-";
  const perms = dir ? "rwxr-xr-x" : "rw-r--r--";
  const size = dir ? "4096" : String(typeof getNode(absPath) === "string" ? (getNode(absPath) as string).length : 0);
  return `${type}${perms}  1 user user ${size.padStart(6)}  Jan 15 10:00  ${name}`;
}

commands.cat = (args, flags) => {
  if (!args.length) return info("cat: reading from stdin (type text then Ctrl+D)");
  const results = [];
  for (const arg of args) {
    const abs = normalizePath(arg);
    if (state.protected.has(abs)) { results.push(`cat: ${arg}: Permission denied`); continue; }
    if (isDir(abs)) { results.push(`cat: ${arg}: Is a directory`); continue; }
    if (!isFile(abs)) { results.push(`cat: ${arg}: No such file or directory`); continue; }
    let content = getNode(abs) as string;
    if (flags.includes("-n")) {
      content = content.split("\n").map((l, i) => `${String(i + 1).padStart(6)}\t${l}`).join("\n");
    }
    results.push(content);
  }
  return out(results.join("\n"));
};

commands.head = (args, flags) => {
  const n = getFlag(flags, "-n") || "10";
  return fileOp(args, content =>
    content.split("\n").slice(0, Number(n)).join("\n")
  );
};

commands.tail = (args, flags) => {
  const n = getFlag(flags, "-n") || "10";
  if (flags.includes("-f")) {
    const res = fileOp(args, c => c.split("\n").slice(-Number(n)).join("\n"));
    return info("tail: -f not supported in simulator (no live files). Showing last lines instead:\n" + (res && 'text' in res ? res.text : ""));
  }
  return fileOp(args, content =>
    content.split("\n").slice(-Number(n)).join("\n")
  );
};

commands.wc = (args, flags) => {
  return fileOp(args, (content, name) => {
    const lines = content.split("\n").length;
    const words = content.trim().split(/\s+/).length;
    const bytes = content.length;
    if (flags.includes("-l")) return `${lines} ${name}`;
    if (flags.includes("-w")) return `${words} ${name}`;
    if (flags.includes("-c")) return `${bytes} ${name}`;
    return `  ${lines}  ${words} ${bytes} ${name}`;
  });
};

commands.grep = (args, flags) => {
  if (!args.length) return err("grep: missing pattern");
  const pattern = args[0];
  const files = args.slice(1);
  const ignoreCase = flags.includes("-i");
  const showLineNums = flags.includes("-n");
  const invertMatch = flags.includes("-v");
  const countOnly = flags.includes("-c");
  const showFiles = flags.includes("-l");

  const regex = new RegExp(pattern, ignoreCase ? "i" : "");

  if (!files.length) return err("grep: no files specified (stdin not supported in simulator)");

  const results = [];
  for (const f of files) {
    const abs = normalizePath(f);
    if (!isFile(abs)) { results.push(`grep: ${f}: No such file or directory`); continue; }
    const lines = (getNode(abs) as string).split("\n");
    const matched = lines
      .map((line, i) => ({ line, i: i + 1, match: regex.test(line) }))
      .filter(({ match }) => invertMatch ? !match : match);

    if (countOnly) { results.push(`${matched.length} ${f}`); continue; }
    if (showFiles && matched.length) { results.push(f); continue; }
    for (const { line, i } of matched) {
      const prefix = files.length > 1 ? f + ":" : "";
      const lineNum = showLineNums ? i + ":" : "";
      results.push(`${prefix}${lineNum}${line}`);
    }
  }
  return results.length ? out(results.join("\n")) : out("");
};

commands.find = (args, flags, rawArgs) => {
  const startArg = args[0] || ".";
  const start = normalizePath(startArg);
  const nameIdx = rawArgs.indexOf("-name");
  const typeIdx = rawArgs.indexOf("-type");
  const namePattern = nameIdx >= 0 ? rawArgs[nameIdx + 1] : null;
  const typeFilter = typeIdx >= 0 ? rawArgs[typeIdx + 1] : null;

  const results: string[] = [];
  function walk(p: string) {
    if (state.deleted.has(p) || state.protected.has(p)) return;
    const entries = listDir(p);
    if (!entries) return;
    for (const name of entries) {
      const child = p === "/" ? "/" + name : p + "/" + name;
      const dir = isDir(child);

      let match = true;
      if (namePattern) {
        const regex = new RegExp("^" + namePattern.replace(/\*/g, ".*").replace(/\?/g, ".") + "$");
        match = match && regex.test(name);
      }
      if (typeFilter === "f") match = match && !dir;
      if (typeFilter === "d") match = match && dir;

      if (match) results.push(child);
      if (dir) walk(child);
    }
  }
  walk(start);
  return results.length ? out(results.join("\n")) : out("");
};

