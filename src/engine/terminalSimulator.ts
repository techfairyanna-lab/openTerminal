function normalizePath(p: string | undefined): string {
  if (!p) return state.cwd;
  if (p.startsWith("~")) p = state.env.HOME + p.slice(1);
  if (!p.startsWith("/")) p = state.cwd + "/" + p;
  const parts = p.split("/").filter(Boolean);
  const resolved: string[] = [];
  for (const part of parts) {
    if (part === ".") continue;
    if (part === "..") resolved.pop();
    else resolved.push(part);
  }
  return "/" + resolved.join("/");
}

function getNode(absPath: string): FSNode | undefined {
  if (state.deleted.has(absPath)) return undefined;
  if (absPath in state.overlay) return state.overlay[absPath];

  if (absPath === "/") return FILESYSTEM;
  const parts = absPath.split("/").filter(Boolean);
  let node: FSNode = FILESYSTEM;
  for (const part of parts) {
    if (node === null) return undefined;
    if (typeof node === "string") return undefined;
    if (!(part in node)) return undefined;
    node = (node as Record<string, FSNode>)[part];
  }
  return node;
}

function isDir(absPath: string): boolean {
  const node = getNode(absPath);
  return node !== undefined && node !== null && typeof node !== "string";
}

function isFile(absPath: string): boolean {
  const node = getNode(absPath);
  return typeof node === "string";
}

function listDir(absPath: string): string[] | null {
  if (!isDir(absPath)) return null;
  const entries = new Set<string>();
  const node = getNode(absPath);

  if (absPath === "/") {
    Object.keys(FILESYSTEM as Record<string, FSNode>).forEach(k => { if (k) entries.add(k); });
  } else {
    if (node && typeof node === "object") {
      Object.keys(node).forEach(k => entries.add(k));
    }
  }

  const prefix = absPath === "/" ? "/" : absPath + "/";
  for (const p of Object.keys(state.overlay)) {
    if (p.startsWith(prefix)) {
      const rest = p.slice(prefix.length);
      if (!rest.includes("/")) entries.add(rest);
    }
  }

  for (const p of state.deleted) {
    if (p.startsWith(prefix)) {
      const rest = p.slice(prefix.length);
      if (!rest.includes("/")) entries.delete(rest);
    }
  }

  return [...entries].filter(Boolean).sort();
}

function parentPath(absPath: string): string {
  const parts = absPath.split("/").filter(Boolean);
  parts.pop();
  return "/" + parts.join("/");
}

function basename(absPath: string): string {
  return absPath.split("/").filter(Boolean).pop() || "/";
}

